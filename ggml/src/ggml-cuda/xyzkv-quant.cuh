// ---- Nearest 2-bit centroid index ----

static __device__ __forceinline__ uint8_t xyzkv_nearest_centroid_2bit(float val) {
    if      (val < XYZKV_MID_2BIT[0]) return 0;
    else if (val < XYZKV_MID_2BIT[1]) return 1;
    else if (val < XYZKV_MID_2BIT[2]) return 2;
    else                              return 3;
}

// ---- Per-block quantize for xyzkv2 (32 elements, expects already-rotated input) ----

static __device__ void quantize_f32_xyzkv2_0_block(const float * __restrict__ src,
                                                    block_xyzkv2_0 * __restrict__ dst) {
    for (int j = 0; j < QK_XYZKV2 / 4; j++) dst->qs[j] = 0;

    for (int j = 0; j < QK_XYZKV2; j++) {
        uint8_t idx = xyzkv_nearest_centroid_2bit(src[j]);
        dst->qs[j / 4] |= (idx & 0x3) << ((j % 4) * 2);
    }
}

// ---- Inline dequant helper: extract one float from xyzkv2 block ----

static __device__ __forceinline__ float xyzkv2_dequant_element(
        const block_xyzkv2_0 * __restrict__ x, int j, float norm) {
    uint8_t idx = (x->qs[j / 4] >> ((j % 4) * 2)) & 0x3;
    return XYZKV_CENTROIDS_2BIT[idx] * norm;
}

